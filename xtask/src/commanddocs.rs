//! `cargo xtask command-docs`: generate `docs/guide/command-reference.md` from
//! the live command registry (`cadaddy-cli commands`).
//!
//! Every `CommandSpec` in the engine is serialised as JSON by the CLI; this
//! xtask formats that into a Markdown reference grouped by menu path so it
//! never drifts from the code.
//!
//! `cargo xtask command-docs --check` regenerates and fails on any diff
//! (used by `cargo xtask ci`).

use std::path::Path;
use std::process::Command;

/// A parsed command entry from the CLI JSON.
struct CmdEntry {
    id: String,
    label: String,
    menu: Vec<String>,
    shortcut: Option<String>,
    aliases: Vec<String>,
    params: String,
    interactive: bool,
}

fn parse_entries(json: &serde_json::Value) -> Vec<CmdEntry> {
    let arr = match json.as_array() {
        Some(a) => a,
        None => return Vec::new(),
    };
    let mut out = Vec::with_capacity(arr.len());
    for v in arr {
        let id = v["id"].as_str().unwrap_or("").to_string();
        let label = v["label"].as_str().unwrap_or("").to_string();
        let menu: Vec<String> = v["menu"].as_array().map(|a| a.iter().filter_map(|x| x.as_str()).map(str::to_string).collect()).unwrap_or_default();
        let shortcut = v["shortcut"].as_str().map(str::to_string);
        let aliases: Vec<String> =
            v["aliases"].as_array().map(|a| a.iter().filter_map(|x| x.as_str()).map(str::to_string).collect()).unwrap_or_default();
        let params = v["params"].as_str().unwrap_or("").to_string();
        let interactive = v["interactive"].as_bool().unwrap_or(false);
        out.push(CmdEntry { id, label, menu, shortcut, aliases, params, interactive });
    }
    out.sort_by(|a, b| a.id.cmp(&b.id));
    out
}

/// Group commands by top-level menu, then format as Markdown.
fn format_reference(entries: &[CmdEntry]) -> String {
    let mut md = String::new();
    md.push_str(
        "# Command Reference\n\n\
         > Auto-generated by `cargo xtask command-docs`. Do not edit by hand.\n\n\
         This is a complete list of every command in CADaddy, generated directly from the\n\
         source code so it stays in sync with each release.\n\n\
         **Legend:** ID is the command-line name you type. Aliases are short forms.\n\
         The params column shows the JSON parameters for programmatic use\n\
         (`engine.execute` / MCP `execute` tool). An asterisk (*) after the label\n\
         means the command also has an interactive prompt sequence.\n\n",
    );

    // Group by top-level menu
    let mut groups: Vec<(String, Vec<&CmdEntry>)> = Vec::new();
    let mut no_menu: Vec<&CmdEntry> = Vec::new();

    for e in entries {
        if e.menu.is_empty() {
            no_menu.push(e);
        } else {
            let top = e.menu[0].clone();
            if let Some(g) = groups.iter_mut().find(|(k, _)| *k == top) {
                g.1.push(e);
            } else {
                groups.push((top, vec![e]));
            }
        }
    }

    // Table of contents
    md.push_str("## Contents\n\n");
    for (name, cmds) in &groups {
        let anchor = name.to_ascii_lowercase().replace(' ', "-");
        md.push_str(&format!("- [{name}](#{anchor}) ({} commands)\n", cmds.len()));
    }
    if !no_menu.is_empty() {
        md.push_str(&format!("- [Other](#other) ({} commands)\n", no_menu.len()));
    }
    md.push_str(&format!("\n**Total: {} commands**\n\n---\n\n", entries.len()));

    // Each group
    for (name, cmds) in &groups {
        md.push_str(&format!("## {name}\n\n"));
        write_table(&mut md, cmds);
        md.push_str("\n---\n\n");
    }

    if !no_menu.is_empty() {
        md.push_str("## Other\n\nCommands not in any menu (scripting, agent, internal).\n\n");
        write_table(&mut md, &no_menu);
        md.push_str("\n---\n\n");
    }

    md
}

fn write_table(md: &mut String, cmds: &[&CmdEntry]) {
    md.push_str("| ID | Label | Menu Path | Aliases | Shortcut | Params |\n");
    md.push_str("|:---|:------|:----------|:--------|:---------|:-------|\n");
    for c in cmds {
        let menu_path = if c.menu.len() > 1 { c.menu[1..].join(" > ") } else { String::new() };
        let aliases = if c.aliases.is_empty() { String::new() } else { c.aliases.iter().map(|a| format!("`{a}`")).collect::<Vec<_>>().join(", ") };
        let shortcut = c.shortcut.as_deref().unwrap_or("");
        let label = if c.interactive { format!("{}*", c.label) } else { c.label.clone() };
        // Escape pipes in params (no truncation: full text is shown)
        let params_display = c.params.replace('|', "\\|");
        md.push_str(&format!("| `{}` | {} | {} | {} | {} | {} |\n", c.id, label, menu_path, aliases, shortcut, params_display));
    }
}

pub const OUT: &str = "docs/guide/command-reference.md";

/// Generate the command reference. With `check` true, regenerate and fail if
/// the committed file differs (CI drift check).
pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let out_path = root.join(OUT);
    // Ensure docs/guide/ exists
    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("mkdir docs/guide: {e}"))?;
    }

    let output = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .current_dir(root)
        .args(["run", "-q", "-p", "cadaddy-cli", "--", "commands"])
        .output()
        .map_err(|e| format!("cadaddy-cli: {e}"))?;
    if !output.status.success() {
        return Err(format!("cadaddy-cli commands failed:\n{}", String::from_utf8_lossy(&output.stderr)));
    }

    let json: serde_json::Value = serde_json::from_slice(&output.stdout).map_err(|e| format!("commands JSON: {e}"))?;
    let entries = parse_entries(&json);
    if entries.is_empty() {
        return Err("no commands found in cadaddy-cli output".to_string());
    }

    let md = format_reference(&entries);

    if check {
        let existing = std::fs::read_to_string(&out_path).unwrap_or_default();
        if existing == md {
            println!("{OUT} is up to date ({} commands)", entries.len());
            Ok(())
        } else {
            // Show a short summary of what changed
            let old_lines: Vec<&str> = existing.lines().collect();
            let new_lines: Vec<&str> = md.lines().collect();
            let mut diffs = 0;
            for (i, (o, n)) in old_lines.iter().zip(new_lines.iter()).enumerate() {
                if o != n && diffs < 5 {
                    eprintln!("  line {i}: -{o}");
                    eprintln!("  line {i}:  +{n}");
                    diffs += 1;
                }
            }
            if old_lines.len() != new_lines.len() {
                eprintln!("  committed: {} lines, generated: {} lines", old_lines.len(), new_lines.len());
            }
            Err(format!("{OUT} is out of date: regenerate with `cargo xtask command-docs`"))
        }
    } else {
        std::fs::write(&out_path, md.as_bytes()).map_err(|e| format!("write {OUT}: {e}"))?;
        println!("wrote {OUT} ({} commands)", entries.len());
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_entries_from_json() {
        let json = serde_json::json!([
            {
                "id": "line",
                "label": "Line",
                "menu": ["Draw", "Line"],
                "shortcut": null,
                "aliases": ["l"],
                "params": "{points: [[x,y],...]}",
                "interactive": true,
                "enabled": true
            },
            {
                "id": "circle",
                "label": "Circle",
                "menu": ["Draw", "Circle", "Center, Radius"],
                "shortcut": null,
                "aliases": ["c"],
                "params": "{center, radius}",
                "interactive": true,
                "enabled": true
            },
            {
                "id": "undo",
                "label": "Undo",
                "menu": [],
                "shortcut": "Ctrl+Z",
                "aliases": ["u"],
                "params": "{}",
                "interactive": false,
                "enabled": true
            }
        ]);
        let entries = parse_entries(&json);
        assert_eq!(entries.len(), 3);
        // Sorted by id
        assert_eq!(entries[0].id, "circle");
        assert_eq!(entries[1].id, "line");
        assert_eq!(entries[2].id, "undo");
        assert!(entries[1].interactive);
        assert!(!entries[2].interactive);
        assert_eq!(entries[2].shortcut.as_deref(), Some("Ctrl+Z"));
    }

    #[test]
    fn format_reference_has_sections() {
        let json = serde_json::json!([
            {
                "id": "line",
                "label": "Line",
                "menu": ["Draw", "Line"],
                "aliases": ["l"],
                "params": "{points}",
                "interactive": true
            },
            {
                "id": "move",
                "label": "Move",
                "menu": ["Modify", "Move"],
                "aliases": ["m"],
                "params": "{delta}",
                "interactive": true
            },
            {
                "id": "delay",
                "label": "Delay",
                "menu": [],
                "aliases": [],
                "params": "{ms}",
                "interactive": false
            }
        ]);
        let entries = parse_entries(&json);
        let md = format_reference(&entries);
        assert!(md.contains("## Draw"), "should have Draw section");
        assert!(md.contains("## Modify"), "should have Modify section");
        assert!(md.contains("## Other"), "should have Other section");
        assert!(md.contains("**Total: 3 commands**"));
        assert!(md.contains("| `line` |"));
        assert!(md.contains("Line*")); // interactive marker
        assert!(!md.contains("Delay*")); // not interactive
    }

    #[test]
    fn write_table_preserves_long_multibyte_params() {
        // A >80-char param string with multi-byte characters must appear in
        // full in the output (no truncation).
        let long_params = "{mode: \u{201c}length\u{201d}, layers: \u{201c}E-*,P-*\u{201d}, waste: percent added (default 0), nested: bool (default true), clipped: bool}".to_string();
        assert!(long_params.len() > 80, "test param string must exceed 80 bytes");

        let entry = CmdEntry {
            id: "takeoff".to_string(),
            label: "Takeoff".to_string(),
            menu: vec!["Tools".to_string(), "Inquiry".to_string()],
            shortcut: None,
            aliases: vec!["qto".to_string()],
            params: long_params.clone(),
            interactive: true,
        };
        let mut md = String::new();
        write_table(&mut md, &[&entry]);
        // The full param text (with pipes escaped) must be present
        let escaped = long_params.replace('|', "\\|");
        assert!(md.contains(&escaped), "write_table must include the full param text, not truncate it:\n{md}");
    }
}
