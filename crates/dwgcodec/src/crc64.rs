fn for_each_in_order(data: &[u8], mut f: impl FnMut(u8)) {
    let (blocks, rest) = data.as_chunks::<8>();
    for b in blocks {
        for i in [6, 7, 4, 5, 2, 3, 0, 1] {
            f(b[i]);
        }
    }
    let order: &[usize] = match rest.len() {
        1 => &[0],
        2 => &[0, 1],
        3 => &[0, 1, 2],
        4 => &[2, 3, 0, 1],
        5 => &[2, 3, 0, 1, 4],
        6 => &[2, 3, 0, 1, 4, 5],
        7 => &[2, 3, 0, 1, 4, 5, 6],
        _ => &[],
    };
    for &i in order {
        if let Some(&x) = rest.get(i) {
            f(x);
        }
    }
}

/// The normal 64-bit CRC of `data` from `seed` (inverted at the end).
pub fn normal(seed: u64, data: &[u8]) -> u64 {
    let mut crc = seed;
    for_each_in_order(data, |x| crc = NORMAL[usize::from(x ^ (crc >> 56) as u8)] ^ (crc << 8));
    !crc
}

/// The mirrored 64-bit CRC of `data` from `seed`.
pub fn mirrored(seed: u64, data: &[u8]) -> u64 {
    let mut crc = seed;
    for_each_in_order(data, |x| crc = MIRRORED[usize::from(x ^ crc as u8)] ^ (crc >> 8));
    crc
}

/// Spec §5.12 UpdateSeed1.
pub fn seed1(seed: u64, len: u64) -> u64 {
    let mut s = seed.wrapping_add(len).wrapping_mul(0x343fd).wrapping_add(0x269ec3);
    s |= s.wrapping_mul(0x343fd << 32).wrapping_add(0x269ec3 << 32);
    !s
}

/// Spec §5.12 UpdateSeed2.
pub fn seed2(seed: u64, len: u64) -> u64 {
    let s = seed.wrapping_add(len).wrapping_mul(0x343fd).wrapping_add(0x269ec3);
    let s = s.wrapping_mul((1 << 32) + 0x343fd).wrapping_add(len.wrapping_add(0x269ec3));
    !s
}
