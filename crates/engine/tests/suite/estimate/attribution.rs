//! Every file under `assets/` has its ATTRIBUTION.md row (author, source, licence).
//!
//! `cargo xtask assets` checks this, but only inside the full `cargo xtask ci`; the engine's own
//! tests run whenever its embedded data changes (the cost books, the public cost pack, the word
//! list), so an unattributed data file fails here, in the same run as the code that ships it.
//! The rule is the xtask's: a path listed as `` `path` `` in ATTRIBUTION.md, or under a folder row
//! (`` `dir/` `` as a table row's first cell).

use std::path::{Path, PathBuf};

/// Folders attributed as a whole: table rows whose first cell is `` `dir/` ``.
fn folder_rows(md: &str) -> Vec<&str> {
    md.lines().filter_map(|l| l.strip_prefix("| `")?.split_once('`').map(|(p, _)| p)).filter(|p| p.ends_with('/')).collect()
}

/// The asset paths (relative, `/`-separated) with no ATTRIBUTION.md entry.
fn unattributed(files: &[String], md: &str) -> Vec<String> {
    let folders = folder_rows(md);
    files.iter().filter(|f| !md.contains(&format!("`{f}`")) && !folders.iter().any(|d| f.starts_with(d))).cloned().collect()
}

/// Every file under `dir`, as paths relative to `root` with `/` separators. Capped (depth and count).
fn files_under(root: &Path, dir: &Path) -> Vec<String> {
    let mut out = Vec::new();
    let mut stack: Vec<(PathBuf, usize)> = vec![(dir.to_path_buf(), 0)];
    while let Some((d, depth)) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&d) else { continue };
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                if depth < 16 {
                    stack.push((p, depth + 1));
                }
            } else if let Ok(rel) = p.strip_prefix(root) {
                out.push(rel.components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("/"));
            }
            if out.len() > 100_000 {
                return out;
            }
        }
    }
    out.sort();
    out
}

#[test]
fn every_shipped_asset_file_has_an_attribution_row() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let md = std::fs::read_to_string(root.join("ATTRIBUTION.md")).expect("ATTRIBUTION.md at the repository root");
    let files = files_under(&root, &root.join("assets"));
    assert!(files.iter().any(|f| f == "assets/costbook/starter.csv"), "the walk finds the embedded cost book: {files:?}");
    let miss = unattributed(&files, &md);
    assert!(miss.is_empty(), "{} asset file(s) lack an ATTRIBUTION.md entry (author, source, licence): {miss:?}", miss.len());
}

#[test]
fn a_new_data_file_without_its_row_is_reported_and_a_folder_row_covers_its_files() {
    let files: Vec<String> =
        ["assets/books/sample_book.csv", "assets/books/sample_map.csv", "assets/generated/a/b.csv", "assets/generatedx/c.csv", "assets/notes.txt"]
            .iter()
            .map(|s| s.to_string())
            .collect();
    let md = "Everything under `assets/notes.txt` is named in prose only.\n\
              | Asset | Author | Source | Licence | Notes |\n\
              | `assets/books/sample_map.csv` | Example contributors | written for the example | MIT | map |\n\
              | `assets/generated/` | Example contributors | generated by a tool | MIT | folder |";
    // Prose naming a path still counts (the xtask's rule); a folder row covers only its own folder.
    assert_eq!(unattributed(&files, md), vec!["assets/books/sample_book.csv".to_string(), "assets/generatedx/c.csv".into()]);
}

#[test]
fn the_walk_lists_nested_files_relative_to_the_root() {
    let tmp = std::env::temp_dir().join(format!("cadaddy-attr-walk-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(tmp.join("assets/deep/er")).expect("temp dirs");
    std::fs::write(tmp.join("assets/top.csv"), "a\n").expect("write");
    std::fs::write(tmp.join("assets/deep/er/inner.json"), "{}").expect("write");
    let got = files_under(&tmp, &tmp.join("assets"));
    let _ = std::fs::remove_dir_all(&tmp);
    assert_eq!(got, vec!["assets/deep/er/inner.json".to_string(), "assets/top.csv".into()]);
}
