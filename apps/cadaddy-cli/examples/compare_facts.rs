//! `cargo run -p cadaddy-cli --example compare_facts -- <repository folder>`: writes
//! `docs/compare-facts.json` and `docs/compare-facts-llms.txt` (see `facts.rs`); run by
//! `cargo xtask compare-facts`.

// `check` is for the claims test.
#[allow(dead_code)]
#[path = "../facts.rs"]
mod facts;

fn main() {
    let root = std::env::args().nth(1).map(std::path::PathBuf::from).unwrap_or_else(|| std::path::PathBuf::from("."));
    let f = facts::compute(&root);
    let json = serde_json::to_string_pretty(&f).unwrap_or_default() + "\n";
    let docs = root.join("docs");
    if let Err(e) = std::fs::write(docs.join("compare-facts.json"), json) {
        eprintln!("compare-facts: {e}");
        std::process::exit(1);
    }
    let llms = format!("# CADaddy facts (generated by `cargo xtask compare-facts`; do not edit by hand)\n\n{}", facts::llms_lines(&f));
    if let Err(e) = std::fs::write(docs.join("compare-facts-llms.txt"), llms) {
        eprintln!("compare-facts: {e}");
        std::process::exit(1);
    }
    println!("compare-facts: {} commands, {} MCP tools, {} languages", f["commands"]["count"], f["mcp"]["count"], f["languages"]["count"]);
}
